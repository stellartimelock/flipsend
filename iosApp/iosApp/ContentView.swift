import SwiftUI
import ComposeApp

/// Root SwiftUI view.
///
/// Embeds the Kotlin Multiplatform / Compose UI via [MainViewController].
/// SwiftUI-only sheets (document picker, QR scanner) are presented here
/// because iOS requires them to originate from UIKit/SwiftUI.
struct ContentView: View {

    @EnvironmentObject private var appState: AppState
    @StateObject private var bridge = IosBridgeViewModel()

    var body: some View {
        ZStack {
            // Compose Multiplatform content
            ComposeView(bridge: bridge.kotlinBridge)
                .ignoresSafeArea(.keyboard)

            // Transparent overlay for SwiftUI-managed sheets
            Color.clear
                .sheet(isPresented: $appState.showDocumentPicker) {
                    FolderPickerSheet { url in
                        appState.showDocumentPicker = false
                        appState.folderPickerCallback?(url)
                        appState.folderPickerCallback = nil
                    }
                }
        }
        .onReceive(bridge.pickFolderRequest) { callback in
            appState.pickFolder(completion: callback)
        }
    }
}

/// UIViewControllerRepresentable that hosts the KMP ComposeUIViewController.
struct ComposeView: UIViewControllerRepresentable {
    let bridge: any PlatformBridge

    func makeUIViewController(context: Context) -> UIViewController {
        // MainViewController is generated by the KMP Gradle plugin from
        // composeApp/src/iosMain/.../MainViewController.kt
        return MainViewController(bridge: bridge)
    }

    func updateUIViewController(_ uiViewController: UIViewController, context: Context) {}
}

/// SwiftUI wrapper for UIDocumentPickerViewController.
/// Gives access to the StellarTimeLock folder as a security-scoped bookmark.
struct FolderPickerSheet: UIViewControllerRepresentable {
    let onPicked: (URL?) -> Void

    func makeCoordinator() -> Coordinator { Coordinator(onPicked: onPicked) }

    func makeUIViewController(context: Context) -> UIDocumentPickerViewController {
        let picker = UIDocumentPickerViewController(forOpeningContentTypes: [.folder])
        picker.delegate = context.coordinator
        picker.allowsMultipleSelection = false
        return picker
    }

    func updateUIViewController(_ uiViewController: UIDocumentPickerViewController, context: Context) {}

    final class Coordinator: NSObject, UIDocumentPickerDelegate {
        let onPicked: (URL?) -> Void
        init(onPicked: @escaping (URL?) -> Void) { self.onPicked = onPicked }

        func documentPicker(_ controller: UIDocumentPickerViewController, didPickDocumentsAt urls: [URL]) {
            guard let url = urls.first else { onPicked(nil); return }
            // Persist a security-scoped bookmark so the app can re-open the folder
            // across launches without re-prompting.
            FolderBookmark.save(url: url)
            onPicked(url)
        }

        func documentPickerWasCancelled(_ controller: UIDocumentPickerViewController) {
            onPicked(nil)
        }
    }
}
