package org.stellartimelock.send.shared

import kotlinx.cinterop.ExperimentalForeignApi
import kotlinx.cinterop.alloc
import kotlinx.cinterop.memScoped
import kotlinx.cinterop.ptr
import kotlinx.cinterop.reinterpret
import kotlinx.cinterop.value
import platform.CoreFoundation.CFArrayCreateMutable
import platform.CoreFoundation.CFArrayAppendValue
import platform.CoreFoundation.CFRelease
import platform.CoreFoundation.kCFAllocatorDefault
import platform.CoreFoundation.kCFTypeArrayCallBacks
import platform.Foundation.NSData
import platform.Foundation.NSString
import platform.Security.SecCertificateCreateWithData
import platform.Security.SecIdentityRef
import platform.Security.SecItemAdd
import platform.Security.SecItemCopyMatching
import platform.Security.SecItemDelete
import platform.Security.SecKeyCreateRandomKey
import platform.Security.kSecAttrApplicationTag
import platform.Security.kSecAttrIsPermanent
import platform.Security.kSecAttrKeyType
import platform.Security.kSecAttrKeySizeInBits
import platform.Security.kSecAttrKeyTypeECSECPrimeRandom
import platform.Security.kSecAttrLabel
import platform.Security.kSecClass
import platform.Security.kSecClassCertificate
import platform.Security.kSecClassIdentity
import platform.Security.kSecPrivateKeyAttrs
import platform.Security.kSecReturnRef
import platform.Security.kSecValueRef

/**
 * Keychain helpers for the FlipSend transport identity.
 *
 * IMPORTANT: The Keychain key stored here is the TRANSPORT identity only —
 * it authenticates peers during the TLS handshake. It is NOT the encryption
 * key for save files. Save files are encrypted with a key derived from the
 * StellarTimeLock seed or a user password (Argon2id/HKDF). The Keychain
 * stores this TLS key merely for persistence; its loss only requires
 * re-pairing, not data loss.
 */
object IosKeychain {

    private const val TAG = "org.stellartimelock.stellarsend.tls.key.v1"
    private const val CERT_LABEL = "FlipSend TLS Identity v1"

    /**
     * Return the [SecIdentityRef] matching [identity].
     *
     * If none exists yet, we:
     *  1. Insert the DER certificate from [identity] into the Keychain.
     *  2. Generate a new permanent EC private key tagged with [TAG].
     *
     * In the common case the private key was generated by [generateIdentity]
     * with `kSecAttrIsPermanent = true`, so both the key and the cert are
     * already present and [SecItemCopyMatching] succeeds on the first try.
     */
    @OptIn(ExperimentalForeignApi::class)
    fun getOrCreate(identity: DeviceIdentity): SecIdentityRef {
        lookupIdentity()?.let { return it }

        // Insert certificate
        val certNsData = identity.certificateBytes.toNSData()
        val certRef = SecCertificateCreateWithData(kCFAllocatorDefault, certNsData)
            ?: throw java.io.IOException("Cannot create SecCertificate from DER bytes.")
        val addCert: Map<Any?, Any?> = mapOf(
            kSecClass to kSecClassCertificate,
            kSecValueRef to certRef,
            kSecAttrLabel to CERT_LABEL
        )
        SecItemAdd(addCert as platform.CoreFoundation.CFDictionaryRef, null)
        CFRelease(certRef)

        // Generate permanent private key (tagged so SecIdentity search finds it)
        val keyAttrs: Map<Any?, Any?> = mapOf(
            kSecAttrKeyType to kSecAttrKeyTypeECSECPrimeRandom,
            kSecAttrKeySizeInBits to 256,
            kSecPrivateKeyAttrs to mapOf(
                kSecAttrIsPermanent to true,
                kSecAttrApplicationTag to TAG.encodeToByteArray().toNSData()
            )
        )
        SecKeyCreateRandomKey(keyAttrs as platform.CoreFoundation.CFDictionaryRef, null)

        return lookupIdentity()
            ?: throw java.io.IOException("SecIdentity not found after Keychain insertion.")
    }

    /** Delete the transport identity from Keychain (called on full reset). */
    @OptIn(ExperimentalForeignApi::class)
    fun deleteAll() {
        val delIdentity: Map<Any?, Any?> = mapOf(
            kSecClass to kSecClassIdentity,
            kSecAttrLabel to CERT_LABEL
        )
        SecItemDelete(delIdentity as platform.CoreFoundation.CFDictionaryRef)
        val delKey: Map<Any?, Any?> = mapOf(
            kSecClass to platform.Security.kSecClassKey,
            kSecAttrApplicationTag to TAG.encodeToByteArray().toNSData()
        )
        SecItemDelete(delKey as platform.CoreFoundation.CFDictionaryRef)
    }

    @OptIn(ExperimentalForeignApi::class)
    private fun lookupIdentity(): SecIdentityRef? {
        val query: Map<Any?, Any?> = mapOf(
            kSecClass to kSecClassIdentity,
            kSecAttrLabel to CERT_LABEL,
            kSecReturnRef to true
        )
        memScoped {
            val result = alloc<platform.CoreFoundation.CFTypeRefVar>()
            val status = SecItemCopyMatching(query as platform.CoreFoundation.CFDictionaryRef, result.ptr)
            if (status == 0) {
                @Suppress("UNCHECKED_CAST")
                return result.value?.reinterpret<platform.Security.OpaqueSecIdentity>()
            }
        }
        return null
    }
}
